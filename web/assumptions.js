/* Реестр допущений модели: что взято из файлов заказчика, что вычислено, а что задано командой. */
(() => {
  const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  const FILE = "Файл заказчика", CALC = "Вычислено из истории", TEAM = "Допущение команды Light";

  window.renderAssumptions = function (el, meta) {
    if (!el) return;
    if (!meta) { el.innerHTML = '<p class="muted">Нет данных</p>'; return; }
    const sc = meta.scenarios || {};
    const leads = Object.values(meta.suppliers || {}).map((s) => `${s.name}: ${Math.round(s.lead * 30)} дн`).join(" · ");
    const z = sc.base ? `A ${sc.base.z.A} · B ${sc.base.z.B} · C ${sc.base.z.C}` : "—";
    const scen = Object.values(sc).map((s) => `${s.label}: спрос ${s.demand > 0 ? "+" : ""}${Math.round(s.demand * 100)}%, поставка +${s.lead_add_days} дн, z ${s.z.A}/${s.z.B}/${s.z.C}`).join("; ");
    const rows = [
      ["Срок поставки", leads, TEAM + " (оценено по датам в файле «Путь ИЭК»)", "да", "дата «заказать до», объём заказа"],
      ["Согласование заказа", `${meta.buffer} дн`, TEAM, "да", "последний безопасный день"],
      ["Период пересмотра", "30 дн", TEAM, "да", "на сколько вперёд заказываем"],
      ["Прогноз прироста рынка", "0 %", TEAM, "да", "прогноз спроса"],
      ["Уровень сервиса по ABC (базовый)", z, TEAM, "через сценарий", "страховой запас"],
      ["Сценарии", scen, TEAM + " (демонстрационные, не вероятности)", "да", "все показатели"],
      ["Категория ABC", "по частоте накладных за 12 мес: 80 % / 15 % / 5 %", CALC, "нет", "уровень сервиса"],
      ["Разовый крупный заказ", "медиана + 6·MAD, ≥ 5 медиан, ≥ 25 % продаж месяца, ≥ 8 накладных; повтор в 4+ мес. или > 20 % месяцев — постоянный оптовик", TEAM, "в экспертном режиме — вкл/выкл", "регулярный спрос"],
      ["Поле клиента", "в выгрузке отсутствует — проверка «крупные продажи одному клиенту» невозможна, разовые заказы ищутся по накладной", FILE, "нет", "поиск разовых заказов"],
      ["Фильтр всплесков (Хампель)", "окно ±3 мес, порог медиана + 3·MAD; месяцы без товара в норму не входят", TEAM, "в экспертном режиме — вкл/выкл", "регулярный спрос"],
      ["Месяцы без товара (stockout)", "доля месяца в наличии 0,1 / 0,4 / 0,6 по остаткам на начало и конец месяца", TEAM, "в экспертном режиме — вкл/выкл", "восстановленный спрос"],
      ["Сезонность", "профиль поставщика из файла «Сезонность» + собственный профиль товара (вес до 60 %)", FILE + " + " + CALC, "в экспертном режиме — вкл/выкл", "прогноз по месяцам"],
      ["Уровень спроса", `среднее за ${meta.levelWindow || 6} мес. без сезонности`, CALC, "нет", "прогноз"],
      ["Тренд", "рост год к году, ограничен −30…+50 %", CALC + " (ограничение — " + TEAM + ")", "в экспертном режиме — вкл/выкл", "прогноз"],
      ["Кратность (MOQ)", "из файлов MOQ; где нет — принята 1", FILE, "нет", "округление заказа"],
      ["Себестоимость", "Systeme Electric — «СС реал»; у IEK цен нет", FILE, "нет", "стоимость заказа, бюджет"],
      ["Товар в пути", "IEK — с датой прихода; SE — без даты, не считается прибывшим", FILE, "в экспертном режиме — вкл/выкл", "объём заказа, дата окончания"],
      ["Текущий остаток", "SE — «Свободный остаток»; IEK — остаток на 01.09 минус продажи с начала месяца", FILE + " + " + CALC, "нет", "все показатели"],
      ["Излишек", "запас больше чем на 6 месяцев", TEAM, "нет", "показатель излишков"],
      ["Горизонт календаря", `${meta.projectionDays} дн`, TEAM, "нет", "даты окончания запаса"],
      ["Минимальная история", `${meta.minHistory} мес`, TEAM, "нет", "статус «Недостаточно данных»"],
    ];
    el.innerHTML = `<p class="c-desc" style="margin-bottom:12px">Какие числа взяты из файлов заказчика, какие вычислены из истории продаж, а какие заданы командой. Допущения команды не выдаются за данные заказчика.</p>
      <div class="table-wrap"><table>
        <thead><tr><th>Параметр</th><th>Значение</th><th>Источник</th><th class="hide-sm">Можно менять</th><th class="hide-sm">На что влияет</th></tr></thead>
        <tbody>${rows.map(([p, v, s, c, i]) => `<tr><td><b>${esc(p)}</b></td><td>${esc(v)}</td><td>${esc(s)}</td><td class="hide-sm">${esc(c)}</td><td class="hide-sm">${esc(i)}</td></tr>`).join("")}</tbody>
      </table></div>`;
  };
})();
